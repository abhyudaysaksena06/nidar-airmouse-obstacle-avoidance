#!/usr/bin/env python3
"""Turn the SolidWorks (sw_urdf_exporter) URDF into the clean ROS 2 xacro used by
nidar_drone_description.

Run it again every time the CAD team re-exports the URDF:

    python3 tools/cad_urdf_to_xacro.py  path/to/exported.urdf
            [--meshes path/to/exported/meshes]

What it changes (masses, inertias, CoMs and joint positions are copied unchanged):
  1. Mesh paths -> ${mesh_uri}/<file>.STL (works in RViz, Gazebo and PX4).
  2. Adds a massless `base_link` root (ROS/PX4 convention; KDL ignores a root with inertia).
  3. Every prop_N_joint becomes `continuous` about +Z (the export had prop_4 fixed).
  4. Collision: each landing-gear leg gets ONE sphere at its foot (found from the
     STL), the frame gets one box, props/sensors/electronics get none. Simple
     shapes give fast, stable ground contact (full meshes were ~30k triangles).
  5. Colours per part so the model is readable in RViz.
"""
import argparse
import os
import shutil
import sys
import xml.etree.ElementTree as ET

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "..", "ros2_ws", "src", "nidar_drone_description")

COLOURS = {  # link-name prefix -> (material name, rgba)
    "dronebase": ("frame_grey", "0.75 0.75 0.78 1"),
    "motor": ("motor_black", "0.10 0.10 0.10 1"),
    "prop": ("prop_orange", "1.0 0.45 0.05 0.9"),
    "landgear": ("gear_black", "0.15 0.15 0.15 1"),
    "FC": ("pcb_green", "0.05 0.45 0.15 1"),
    "IMU": ("pcb_blue", "0.10 0.25 0.80 1"),
    "RPI": ("pcb_green", "0.05 0.45 0.15 1"),
    "ESC": ("esc_red", "0.75 0.10 0.10 1"),
    "lidar": ("sensor_cyan", "0.0 0.75 0.85 1"),
    "TOF": ("sensor_cyan", "0.0 0.75 0.85 1"),
    "ultra": ("sensor_cyan", "0.0 0.75 0.85 1"),
    "MPCamera": ("sensor_cyan", "0.0 0.75 0.85 1"),
}


def colour_for(link):
    for prefix, c in COLOURS.items():
        if link.startswith(prefix):
            return c
    return ("frame_grey", "0.75 0.75 0.78 1")


def read_stl(path):
    """Vertices of a binary or ASCII STL (no extra libraries needed)."""
    with open(path, "rb") as fh:
        data = fh.read()
    if data[:5].lower() == b"solid" and b"facet" in data[:400]:
        pts = [list(map(float, ln.split()[1:4])) for ln in data.decode(errors="ignore").splitlines()
               if ln.strip().startswith("vertex")]
        return np.array(pts)
    n = int(np.frombuffer(data[80:84], "<u4")[0])
    rec = np.frombuffer(data[84:84 + n * 50], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))
    return rec["v"].reshape(-1, 3).astype(float)


def foot_sphere(stl):
    """Centre and radius of a sphere sitting where the leg touches the ground."""
    v = read_stl(stl)
    zmin = v[:, 2].min()
    low = v[v[:, 2] < zmin + 0.004]
    cx, cy = low[:, 0].mean(), low[:, 1].mean()
    r = max(0.005, min(0.02, 0.5 * max(np.ptp(low[:, 0]), np.ptp(low[:, 1]))))
    return (cx, cy, zmin + r), r


def f(v):
    """Tidy a number: round CAD noise like 2.2624E-12 to 0."""
    x = float(v)
    if abs(x) < 1e-9:
        return "0"
    return f"{x:.6g}"


def vec(s):
    return " ".join(f(t) for t in s.split())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("urdf")
    ap.add_argument("--meshes", help="exported meshes folder to copy into the package")
    ap.add_argument("--out", default=os.path.join(PKG, "urdf", "nidar_drone_body.xacro"))
    a = ap.parse_args()
    a.mesh_dir = a.meshes or os.path.join(PKG, "meshes")

    root = ET.parse(a.urdf).getroot()
    out = []
    w = out.append
    w('<?xml version="1.0"?>')
    w("<!-- GENERATED by tools/cad_urdf_to_xacro.py from the SolidWorks export.")
    w("     Do not edit by hand: re-export from CAD and re-run the script. -->")
    w('<robot xmlns:xacro="http://www.ros.org/wiki/xacro">')
    w('  <xacro:macro name="nidar_drone_body" params="mesh_uri">')
    used = {}
    for link in root.findall("link"):
        used[colour_for(link.get("name"))[0]] = colour_for(link.get("name"))[1]
    for name, rgba in used.items():
        w(f'    <material name="{name}"><color rgba="{rgba}"/></material>')

    w('    <link name="base_link"/>')
    w('    <joint name="base_to_frame" type="fixed">')
    w('      <parent link="base_link"/><child link="dronebase_link"/>')
    w('      <origin xyz="0 0 0" rpy="0 0 0"/>')
    w("    </joint>")

    for link in root.findall("link"):
        n = link.get("name")
        inert = link.find("inertial")
        o = inert.find("origin")
        m = inert.find("mass").get("value")
        i = inert.find("inertia").attrib
        mesh = os.path.basename(link.find("visual/geometry/mesh").get("filename"))
        vo = link.find("visual/origin")
        w(f'    <link name="{n}">')
        w("      <inertial>")
        w(f'        <origin xyz="{vec(o.get("xyz"))}" rpy="{vec(o.get("rpy"))}"/>')
        w(f'        <mass value="{f(m)}"/>')
        w("        <inertia " + " ".join(f'{k}="{f(i[k])}"' for k in
                                         ("ixx", "ixy", "ixz", "iyy", "iyz", "izz")) + "/>")
        w("      </inertial>")
        w("      <visual>")
        w(f'        <origin xyz="{vec(vo.get("xyz"))}" rpy="{vec(vo.get("rpy"))}"/>')
        w(f'        <geometry><mesh filename="${{mesh_uri}}/{mesh}"/></geometry>')
        w(f'        <material name="{colour_for(n)[0]}"/>')
        w("      </visual>")
        if n.startswith("landgear"):
            (cx, cy, cz), r = foot_sphere(os.path.join(a.mesh_dir, mesh))
            w("      <collision>")
            w(f'        <origin xyz="{cx:.4f} {cy:.4f} {cz:.4f}" rpy="0 0 0"/>')
            w(f'        <geometry><sphere radius="{r:.4f}"/></geometry>')
            w("      </collision>")
        elif n == "dronebase_link":
            # frame plates: x +-0.242, y +-0.048, z 0..0.082 (from the STL bounds)
            w("      <collision>")
            w('        <origin xyz="0 0 0.041" rpy="0 0 0"/>')
            w('        <geometry><box size="0.484 0.096 0.082"/></geometry>')
            w("      </collision>")
        w("    </link>")

    for j in root.findall("joint"):
        n = j.get("name")
        parent = j.find("parent").get("link")
        child = j.find("child").get("link")
        o = j.find("origin")
        is_prop = child.startswith("prop_")
        typ = "continuous" if is_prop else "fixed"
        w(f'    <joint name="{n}" type="{typ}">')
        w(f'      <origin xyz="{vec(o.get("xyz"))}" rpy="{vec(o.get("rpy"))}"/>')
        w(f'      <parent link="{parent}"/><child link="{child}"/>')
        if is_prop:
            w('      <axis xyz="0 0 1"/>')
            w('      <dynamics damping="0.0001"/>')
        w("    </joint>")
    w("  </xacro:macro>")
    w("</robot>")

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", os.path.abspath(a.out))

    if a.meshes:
        dst = os.path.join(PKG, "meshes")
        os.makedirs(dst, exist_ok=True)
        for fn in os.listdir(a.meshes):
            if fn.lower().endswith(".stl"):
                shutil.copy(os.path.join(a.meshes, fn), dst)
        print("copied meshes to", os.path.abspath(dst))


if __name__ == "__main__":
    sys.exit(main())
