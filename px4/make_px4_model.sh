#!/usr/bin/env bash
# Build the PX4/Gazebo model folder px4/models/nidar_drone from the URDF xacro.
# Needs: ROS 2 (xacro) and Gazebo (gz) sourced.  Usage: bash px4/make_px4_model.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
PKG="$HERE/../ros2_ws/src/nidar_drone_description"
OUT="$HERE/models/nidar_drone"
mkdir -p "$OUT/meshes"
cp "$PKG"/meshes/*.STL "$OUT/meshes/"
TMP="$(mktemp -d)"
xacro "$PKG/urdf/nidar_drone.urdf.xacro" px4:=true mesh_uri:=model://nidar_drone/meshes > "$TMP/nidar_drone.urdf"
gz sdf -p "$TMP/nidar_drone.urdf" 2>/dev/null > "$OUT/model.sdf"
grep -q "<model name='nidar_drone'" "$OUT/model.sdf" || { echo "gz sdf conversion failed"; exit 1; }
cat > "$OUT/model.config" <<CFG
<?xml version="1.0"?>
<model>
  <name>nidar_drone</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>NIDAR quadrotor from the team CAD (generated by px4/make_px4_model.sh)</description>
</model>
CFG
rm -rf "$TMP"
echo "PX4 model written to $OUT"
